"""Create/check lossless WebP runtime copies; never modify generated PNG masters.

Requires Pillow==11.3.0. Run from any directory; --check validates checked-in
derivatives against the same premultiplied-alpha Lanczos resize recipe.
"""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image, __version__

ROOT = Path(__file__).resolve().parents[1]
PUBLIC = ROOT / "public"
OUT = PUBLIC / "assets/nutriserve/runtime"
REGISTRY = ROOT / "src/features/nutriserve/assets/runtimeImages.ts"

def digest(data):
    return hashlib.sha256(data).hexdigest()

def resized(source, size):
    # Premultiplication prevents hidden RGB in transparent padding making fringes.
    return source.convert("RGBa").resize(size, Image.Resampling.LANCZOS).convert("RGBA")

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    assert __version__ == "11.3.0", "Use pinned Pillow==11.3.0"
    families = [
        ("characters", "manifest.json", "characters", [96, 360, 720]),
        ("garnishes", "garnishes/manifest.json", "assets", [192]),
        ("food", "food/manifest.json", "assets", [512]),
    ]
    entries = []
    expected = json.loads((OUT / "manifest.json").read_text()) if args.check else None
    OUT.mkdir(parents=True, exist_ok=True)
    for family, filename, key, sizes in families:
        assets = json.loads((PUBLIC / "assets/nutriserve" / filename).read_text())[key]
        for asset in assets:
            source_path = PUBLIC / asset["path"].lstrip("/")
            raw = source_path.read_bytes()
            assert digest(raw) == asset["sha256"], f"Master changed: {source_path}"
            with Image.open(source_path) as image:
                source = image.convert("RGBA")
            variants = []
            for edge in sizes:
                scale = edge / (source.height if family == "characters" else max(source.size))
                size = tuple(round(n * scale) for n in source.size)
                pixels = resized(source, size)
                dest = OUT / f"{source_path.stem}-{edge}.webp"
                if not args.check:
                    pixels.save(dest, "WEBP", lossless=True, exact=True, method=6)
                with Image.open(dest) as decoded:
                    assert decoded.size == size
                    assert decoded.convert("RGBA").tobytes() == pixels.tobytes(), f"Pixel mismatch: {dest}"
                blob = dest.read_bytes()
                variants.append({"path": "/" + dest.relative_to(PUBLIC).as_posix(),
                                 "width": size[0], "height": size[1], "bytes": len(blob),
                                 "sha256": digest(blob), "rgbaSha256": digest(pixels.tobytes())})
            entries.append({"id": asset["id"], "family": family, "source": asset["path"],
                            "sourceSha256": digest(raw), "sourceBytes": len(raw),
                            "sourceWidth": source.width, "sourceHeight": source.height,
                            "variants": variants})
    manifest = {"version": 1, "recipe": "Pillow 11.3.0; premultiplied RGBA Lanczos resize; lossless WebP exact=True method=6; no crop or anchor changes", "assets": entries}
    registry = {entry["source"]: [{k: v[k] for k in ("path", "width", "height")} for v in entry["variants"]] for entry in entries}
    ts = "// Generated by scripts/optimize-nutriserve-assets.py. Coordinates stay in master space.\n"
    ts += "export const RUNTIME_IMAGES = " + json.dumps(registry, indent=2) + " as const;\n"
    ts += "export function runtimeVariants(source: string) {\n  return Object.hasOwn(RUNTIME_IMAGES, source) ? RUNTIME_IMAGES[source as keyof typeof RUNTIME_IMAGES] : undefined;\n}\n"
    if args.check:
        assert manifest == expected, "Runtime manifest drift"
        assert REGISTRY.read_text(encoding="utf-8") == ts, "Runtime registry drift"
    else:
        (OUT / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")
        REGISTRY.write_text(ts, encoding="utf-8", newline="\n")
    for family, *_ in families:
        rows = [e for e in entries if e["family"] == family]
        masters = sum(e["sourceBytes"] for e in rows)
        variants = sum(v["bytes"] for e in rows for v in e["variants"])
        print(f"{family}: {len(rows)} masters {masters:,} bytes; all runtime variants {variants:,} bytes")
    print(f"PASS {len(entries)} masters / {sum(len(e['variants']) for e in entries)} variants: hashes, dimensions and exact resized RGBA")

if __name__ == "__main__":
    main()
